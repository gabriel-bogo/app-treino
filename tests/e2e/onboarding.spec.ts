test('C11: mudar os músculos de cada treino na proposta do plano', async ({ page }) => {
  await fazerOnboarding(page, { nivel: 'Intermediário', dias: '5', enfases: ['Superiores'], aprovar: false })
  await expect(page.getByText('Treino A · Ombros e tríceps', { exact: true })).toBeVisible()
  // Treino A: peito + tríceps (o ombro sai)
  await page.getByRole('button', { name: 'Mudar músculos deste treino' }).first().click()
  const dialogo = page.getByRole('dialog')
  await expect(dialogo.getByRole('button', { name: 'Ombros', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await dialogo.getByRole('button', { name: 'Ombros', exact: true }).click()
  await dialogo.getByRole('button', { name: 'Peito', exact: true }).click()
  await dialogo.getByRole('button', { name: 'Salvar e remontar o treino' }).click()
  await expect(page.getByText('Treino A · Peito e tríceps', { exact: true })).toBeVisible()
  // Treino B: ombros no lugar do peito
  await page.getByRole('button', { name: 'Mudar músculos deste treino' }).nth(1).click()
  await dialogo.getByRole('button', { name: 'Peito', exact: true }).click()
  await dialogo.getByRole('button', { name: 'Ombros', exact: true }).click()
  await dialogo.getByRole('button', { name: 'Salvar e remontar o treino' }).click()
  await expect(page.getByText('Treino B · Costas, ombros e bíceps', { exact: true })).toBeVisible()
  const treinoA = page.getByTestId('treino-do-plano').first()
  await expect(treinoA.getByRole('heading', { name: 'Peito' })).toBeVisible()
  await expect(treinoA.getByRole('heading', { name: 'Ombros' })).toHaveCount(0)
  // continua valendo depois de aprovar (aba Plano)
  await page.getByRole('button', { name: 'Aprovar plano' }).click()
  await page.goto('/#/plano')
  await expect(page.getByText('Treino A · Peito e tríceps', { exact: true })).toBeVisible()
  // voltar ao que o app sugere
  await page.getByRole('button', { name: 'Mudar músculos deste treino' }).first().click()
  await dialogo.getByRole('button', { name: 'Voltar à divisão sugerida pelo app' }).click()
  await expect(page.getByText('Treino A · Ombros e tríceps', { exact: true })).toBeVisible()
})

test('data de nascimento digitável com máscara DD/MM/AAAA', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Li e entendi o aviso').check()
  await page.getByRole('button', { name: 'Começar' }).click()
  const campo = page.getByLabel('Data de nascimento')
  await campo.pressSequentially('31022000')
  await expect(campo).toHaveValue('31/02/2000')
  await page.getByRole('button', { name: 'Continuar' }).click()
  await expect(page.getByText('Digite uma data válida no formato DD/MM/AAAA.')).toBeVisible()
  await campo.fill('')
  await campo.pressSequentially('08071987')
  await expect(campo).toHaveValue('08/07/1987')
})

